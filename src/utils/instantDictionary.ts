/**
 * Normalizes an English word (strip punctuation, lowercases, handles common suffixes)
 * and looks it up in the instant offline dictionary in 0 milliseconds.
 */
export function lookupInstantWord(rawWord: string): DictionaryEntry | null {
  if (!rawWord) return null;
  const clean = rawWord.toLowerCase().replace(/^[.,!?;:'"“”()]+|[.,!?;:'"“”()]+$/g, "").trim();
  if (!clean || clean.length < 2) return null;

  // Direct exact match
  if (INSTANT_DICTIONARY[clean]) {
    return INSTANT_DICTIONARY[clean];
  }

  // Handle plural 's' or 'es' (e.g., 'apples' -> 'apple')
  if (clean.endsWith("s") && clean.length > 3) {
    const singular = clean.slice(0, -1);
    if (INSTANT_DICTIONARY[singular]) {
      return INSTANT_DICTIONARY[singular];
    }
  }

  // Handle possessive 's
  if (clean.endsWith("'s")) {
    const base = clean.slice(0, -2);
    if (INSTANT_DICTIONARY[base]) {
      return INSTANT_DICTIONARY[base];
    }
  }

  // Handle '-ing' (e.g. 'talking' -> 'talk')
  if (clean.endsWith("ing") && clean.length > 4) {
    const base = clean.slice(0, -3);
    if (INSTANT_DICTIONARY[base]) {
      return INSTANT_DICTIONARY[base];
    }
    const baseWithE = base + "e";
    if (INSTANT_DICTIONARY[baseWithE]) {
      return INSTANT_DICTIONARY[baseWithE];
    }
  }

  // Handle '-ed' (e.g. 'talked' -> 'talk')
  if (clean.endsWith("ed") && clean.length > 4) {
    const base = clean.slice(0, -2);
    if (INSTANT_DICTIONARY[base]) {
      return INSTANT_DICTIONARY[base];
    }
    const baseWithD = clean.slice(0, -1);
    if (INSTANT_DICTIONARY[baseWithD]) {
      return INSTANT_DICTIONARY[baseWithD];
    }
  }

  return null;
}
